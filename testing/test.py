BASE = 2**52

def decimal(digits):
    return sum(digit * (BASE**i) for i, digit in enumerate(digits))

a = [0, 1125899906842624, 3035803724855868, 1002907214716714, 3961622941912619, 2644535368401609, 4794036]
b = [4000000000000000]

a = decimal(a)
b = decimal(b)

print(decimal([0, 4419942254379008, 1218062511332401, 2252745923636380, 1562451958731451, 5397605]))
print(a // b)